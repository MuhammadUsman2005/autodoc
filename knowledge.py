# ---------- small helper functions ----------
def get_fault(key):
    """Return the fault tuple as a dictionary so fields can be read by name."""
    name, system, severity, cost, diy, causes, steps, precaution = FAULTS[key]
    return {
        "name": name,
        "system": system,                 # E, B, L, T or C
        "severity": severity,             # 1 = Low, 2 = Medium, 3 = High
        "cost_low": cost[0],
        "cost_high": cost[1],
        "diy": diy,                       # True if the owner can fix it
        "causes": causes,
        "steps": steps.split("|"),        # list of repair steps
        "precaution": precaution,
    }


def split_rule(rule):
    """A rule looks like (fault, cond1, cond2, ...). Return (fault, [conditions])."""
    return rule[0], list(rule[1:])